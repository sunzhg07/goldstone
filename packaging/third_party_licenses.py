#!/usr/bin/env python3
"""Writes THIRD_PARTY_LICENSES.md: the licenses and copyright notices of
everything compiled into the goldstone binary — every crate (on all
platforms) and the embedded fonts (label fonts from typst-assets, user
interface fonts from epaint_default_fonts).

    python3 packaging/third_party_licenses.py -o THIRD_PARTY_LICENSES.md

Uses only `cargo metadata` and the crate sources cargo has downloaded
(run `cargo fetch` first). For crates that declare a license but ship no
license file, the standard text from packaging/licenses/ is used, with the
crate's authors as copyright holders. The release workflow regenerates the
file before building, and the binary embeds it (`goldstone licenses`,
Help ▸ About).
"""

import hashlib
import json
import os
import re
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
STANDARD = os.path.join(HERE, "licenses")
LICENSE_FILE = re.compile(r"^(LICEN[CS]E|COPYING|NOTICE|COPYRIGHT|UNLICENSE)", re.I)
# Font licenses live in subdirectories of these crates.
FONT_DIRS = {"epaint_default_fonts": ["fonts"], "typst-assets": []}
# For crates without license files: which licence of an "A OR B" to show.
PREFERENCE = ["MIT", "Apache-2.0", "Zlib", "BSL-1.0", "0BSD"]


def metadata():
    out = subprocess.run(
        ["cargo", "metadata", "--format-version", "1", "--locked"],
        check=True, capture_output=True, text=True,
    ).stdout
    return json.loads(out)


def shipped_packages(meta):
    """Packages reachable from the goldstone binary (normal and build
    dependencies, all platforms), without our own workspace crates."""
    nodes = {n["id"]: n for n in meta["resolve"]["nodes"]}
    pkgs = {p["id"]: p for p in meta["packages"]}
    root = next(p["id"] for p in meta["packages"] if p["name"] == "goldstone")
    seen, stack = set(), [root]
    while stack:
        i = stack.pop()
        if i in seen:
            continue
        seen.add(i)
        for dep in nodes[i]["deps"]:
            if any(k["kind"] in (None, "build") for k in dep["dep_kinds"]):
                stack.append(dep["pkg"])
    ours = set(meta["workspace_members"])
    return sorted((pkgs[i] for i in seen - ours), key=lambda p: (p["name"], p["version"]))


def license_files(pkg):
    root = os.path.dirname(pkg["manifest_path"])
    files = sorted(f for f in os.listdir(root) if LICENSE_FILE.match(f))
    if pkg.get("license_file") and pkg["license_file"] not in files:
        files.append(pkg["license_file"])
    found = [(f, os.path.join(root, f)) for f in files if os.path.isfile(os.path.join(root, f))]
    for sub in FONT_DIRS.get(pkg["name"], []):
        d = os.path.join(root, sub)
        for f in sorted(os.listdir(d)):
            if f.endswith(".txt"):
                found.append((f"{sub}/{f}", os.path.join(d, f)))
    return found


def chosen_standard(expr):
    """The standard license to show for a license expression."""
    ids = re.findall(r"[A-Za-z0-9.\-]+", expr or "")
    for want in PREFERENCE:
        if want in ids:
            return want
    return None


def read(path):
    with open(path, encoding="utf-8", errors="replace") as f:
        return f.read().strip("\n")


def main():
    meta = metadata()
    pkgs = shipped_packages(meta)
    out = []
    w = out.append
    w("# Third-party licenses\n")
    w("Goldstone itself is MIT-licensed (see LICENSE). The `goldstone` program")
    w("contains the following third-party software and fonts, whose licenses and")
    w("copyright notices are reproduced below. This file is generated by")
    w("`packaging/third_party_licenses.py`.\n")

    w("## Fonts\n")
    w("| Font | Used for | License | Source |")
    w("|---|---|---|---|")
    w("| New Computer Modern (NewCM10, NewCMMath) | diagram labels | GUST Font License | typst-assets |")
    w("| Libertinus Serif | label text fallback | SIL Open Font License 1.1 | typst-assets |")
    w("| DejaVu Sans Mono | label monospace, editor symbols | Bitstream Vera license; DejaVu changes public domain | typst-assets |")
    w("| Ubuntu Light | editor interface | Ubuntu Font Licence 1.0 | epaint_default_fonts |")
    w("| Hack | editor interface (monospace) | MIT; DejaVu parts public domain | epaint_default_fonts |")
    w("| Noto Emoji | editor interface | SIL Open Font License 1.1 | epaint_default_fonts |")
    w("| emoji-icon-font, egui-icons | editor interface | MIT | epaint_default_fonts |")
    w("| Noto Sans SC | web version only: Chinese interface (fetched on demand) | SIL Open Font License 1.1 | notofonts/noto-cjk (license next to the font on the site) |")
    w("\nTheir full license texts are under the crates `typst-assets` (NOTICE) and")
    w("`epaint_default_fonts` (fonts/*.txt) below.\n")

    w("## Crates\n")
    w(f"{len(pkgs)} crates. Where the same license text appears more than once it is")
    w("printed once and referred to afterwards.\n")
    w("| Crate | Version | License |")
    w("|---|---|---|")
    for p in pkgs:
        w(f"| {p['name']} | {p['version']} | {p.get('license') or 'see files'} |")
    w("")

    printed = {}  # text hash -> where it was printed
    standard_used = set()
    for p in pkgs:
        name = f"{p['name']} {p['version']}"
        w(f"### {name}\n")
        w(f"License: {p.get('license') or 'see below'}  ")
        if p.get("repository"):
            w(f"Source: {p['repository']}  ")
        authors = ", ".join(a.split(" <")[0] for a in p.get("authors") or [])
        files = license_files(p)
        if not files:
            std = chosen_standard(p.get("license"))
            holder = authors or f"the {p['name']} authors"
            w(f"Copyright (c) {holder}  ")
            if std:
                standard_used.add(std)
                w(f"No license file in the crate; the {std} license applies, text in")
                w(f"[Standard license texts](#standard-license-texts).\n")
            else:
                w("No license file in the crate.\n")
            continue
        w("")
        for label, path in files:
            text = read(path)
            h = hashlib.sha256(" ".join(text.split()).encode()).hexdigest()
            if h in printed:
                w(f"`{label}`: same text as in {printed[h]}.\n")
                continue
            printed[h] = f"{name} ({label})"
            w(f"`{label}`:\n")
            w("```text")
            w(text.replace("```", "'''"))
            w("```\n")

    w("## Standard license texts\n")
    for std in sorted(standard_used):
        w(f"### {std}\n")
        w("```text")
        w(read(os.path.join(STANDARD, f"{std}.txt")))
        w("```\n")
    text = "\n".join(out) + "\n"
    if len(sys.argv) > 2 and sys.argv[1] == "-o":
        with open(sys.argv[2], "w", encoding="utf-8", newline="\n") as f:
            f.write(text)
    else:
        sys.stdout.write(text)


if __name__ == "__main__":
    main()
